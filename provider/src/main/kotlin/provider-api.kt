// Depth-check bail-out (see common/awakener.kt's per-dispatch decrement) needs its sentinel's TYPE to be
// public, since it's exposed as $decoroutinator$checksumFailedMarker's return type on the public
// DecoroutinatorSpec interface - Kotlin won't let a public member expose an internal type. The
// Any?.isChecksumFailedMarker Boolean extension used to test a value against this marker stays internal
// in utils-provider.kt (used only by plain compiled Kotlin code - resume() there and awakener.kt's
// top-level retry check - never by generated bytecode, which instead fetches this marker via
// $decoroutinator$checksumFailedMarker and compares by reference directly); only the marker object
// itself needs to live here, publicly.
object ChecksumFailedMarker

@Suppress("PrivatePropertyName", "FunctionName")
open class SharedSpec: DecoroutinatorSpec {
    @Transient private var `$decoroutinator$accessor`: BaseContinuationAccessor? = null
    @Transient private var `_$decoroutinator$lineNumber`: Int = 0
    @Transient private var `_$decoroutinator$nextSpec`: DecoroutinatorSpec? = null
    @Transient private var `_$decoroutinator$nextSpecHandle`: MethodHandle? = null
    @Transient private var `$decoroutinator$nextContinuation`: Any? = null

    @Suppress("unused")
    fun `$decoroutinator$init`(
        accessor: BaseContinuationAccessor,
        lineNumber: Int,
        nextSpec: DecoroutinatorSpec?,
        nextSpecHandle: MethodHandle?,
        nextContinuation: Any?
    ) {
        `$decoroutinator$accessor` = accessor
        `_$decoroutinator$lineNumber` = lineNumber
        `_$decoroutinator$nextSpec` = nextSpec
        `_$decoroutinator$nextSpecHandle` = nextSpecHandle
        `$decoroutinator$nextContinuation` = nextContinuation
    }

    override val `$decoroutinator$resumeCookie`: Any?
        get() = `$decoroutinator$nextContinuation`

    override fun `$decoroutinator$getResumeChecksum`(resumeChecksum: Int, resumeCookie: Any?): Int =
        if (doVerifySharedSpec && resumeCookie != null) {
            resumeChecksum minusKey resumeCookie.intIdentity
        } else {
            resumeChecksum
        }

    override val `$decoroutinator$lineNumber`: Int
        get() = `_$decoroutinator$lineNumber`

    override val `$decoroutinator$nextSpecHandle`: MethodHandle?
        get() = `_$decoroutinator$nextSpecHandle`

    override val `$decoroutinator$nextSpec`: DecoroutinatorSpec?
        get() = `_$decoroutinator$nextSpec`

    override fun `$decoroutinator$resume`(
        result: Any?,
        resumeChecksum: Int,
        depthChecksum: Int,
        resumeCookie: Any?
    ): Any? =
        resume(result, resumeChecksum, resumeCookie) { baseContinuation, resultCopy ->
            provider.callInvokeSuspendIfResultIsNotCoroutineSuspended(
                baseContinuation = baseContinuation,
                accessor = `$decoroutinator$accessor`!!,
                result = resultCopy
            )
        }
}

