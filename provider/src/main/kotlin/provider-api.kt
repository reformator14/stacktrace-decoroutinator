    val `$decoroutinator$resumeCookie`: Any?

    val `$decoroutinator$checksumFailedMarker`: ChecksumFailedMarker
        get() = ChecksumFailedMarker

    fun `$decoroutinator$getResumeChecksum`(resumeChecksum: Int, resumeCookie: Any?): Int

    val `$decoroutinator$lineNumber`: Int

    val `$decoroutinator$nextSpecHandle`: MethodHandle?

